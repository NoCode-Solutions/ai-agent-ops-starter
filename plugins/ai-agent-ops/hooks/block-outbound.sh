#!/bin/bash
# PreToolUse(Bash): 取り消せない外向きの操作を、実行の直前に機械で拒否する。
#
# 考え方: ルールファイルに「送信するな」と書くだけでは、状況次第で例外扱いされる。
#         指示ではなく仕組みで止める。ただしこれは最後の砦であって、判断の代わりではない。
#         塞いでいないパターンは必ず残るので、ルール側の記述は緩めない。
#
# 使い方: .claude/settings.json の hooks.PreToolUse に絶対パスで登録し、実行権限を付ける。
#         chmod +x block-outbound.sh

CMD=$(jq -r '.tool_input.command // ""' 2>/dev/null)
[ -z "$CMD" ] && exit 0

# 改行と連続空白を潰して1行にする。パイプやセミコロンで繋いだ迂回も拾えるようにする。
FLAT=$(printf '%s' "$CMD" | tr '\n' ' ' | tr -s ' ')

deny() {
  cat >&2 <<EOF
【ブロック】このコマンドは取り消せない操作を含むため実行できません。

  $1

次のどちらかにしてください。
  1. 実行内容を提示して、人の承認を待つ（推奨）
  2. 下書き・dry-run として保存する

このフックの実体: ${BASH_SOURCE[0]}
EOF
  exit 2
}

# --- 塞ぐときは、同じ「外に出す」でも経路ごとに書く ---
# 1) CLI のサブコマンド
# 2) API のエンドポイントへの直接アクセス
# 3) 言語のライブラリ経由
# 1つ塞いでも別の道が残っていれば、止めたことにならない。
#
# 下の <...> は自分の環境で使っているコマンド名・エンドポイントに置き換える。
# 実際のパターンをこのファイルに書くと、このフック自身が
# 「そのパターンを含むコマンド」として拒否される点に注意する
# （雛形では伏せ字にしてあるのはそのため）。

case "$FLAT" in
  # 1) CLI
  *"<送信サブコマンド>"*)          deny "CLIの送信サブコマンド" ;;

  # 2) API のエンドポイント
  *"<送信エンドポイントのパス>"*)  deny "APIの送信エンドポイント" ;;

  # 3) ライブラリ経由
  *"<メール送信ライブラリの関数名>"*) deny "ライブラリ経由の送信" ;;
esac

# --- 破壊的な操作 ---
case "$FLAT" in
  *"rm -rf /"*)                    deny "ルート配下の再帰削除" ;;
  *"git push --force"*)            deny "強制プッシュ" ;;
  *"<本番デプロイのコマンド>"*)    deny "本番デプロイ" ;;
esac

exit 0
